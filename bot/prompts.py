# Промпт собирается один раз при импорте: профиль компании к этому моменту загружен.
SYSTEM_PROMPT = system_prompt()


def build_system_blocks(
    index_text: str,
    cache_ttl: str = "1h",
    links_text: str = "",
    people_text: str = "",
) -> list[dict[str, Any]]:
    """Системный префикс одним кэшируемым блоком. Порядок склейки важен: что меняется чаще, идёт позже."""
    return [
        {
            "type": "text",
            "text": SYSTEM_PROMPT + index_text + links_text + people_text,
            "cache_control": {"type": "ephemeral", "ttl": cache_ttl},
        }
    ]
