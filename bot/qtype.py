def parse_intent(answer: str) -> str | None:
    """Ответ модели → намерение. None — не разобрали (падаем в ВОПРОС)."""
    head = " ".join((answer or "").split()).upper().strip(".:!— \"'«»*")
    for label, intent in INTENT_BY_LABEL.items():
        if head.startswith(label):
            return intent
    return None

