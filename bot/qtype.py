_LABEL_RE = re.compile("|".join(LABELS.values()))


def classifier_prompt(question: str) -> str:
    body = (question or "").strip()
    if len(body) > MAX_QUESTION:
        body = body[:MAX_QUESTION] + f"\n…[обрезано, всего {len(question)} символов]"
    return (
        "Определи тип запроса и ответь одним словом.\n\n"
        f"ЗАПРОС СОТРУДНИКА:\n<<<НАЧАЛО ДАННЫХ>>>\n{body}\n<<<КОНЕЦ ДАННЫХ>>>"
    )


def parse_type(raw: str) -> str | None:
    """Первое встреченное название типа (подстрокой: модель дописывает пояснения). None — ответ мимо списка."""
    match = _LABEL_RE.search((raw or "").upper())
    return BY_LABEL[match.group(0)] if match else None


