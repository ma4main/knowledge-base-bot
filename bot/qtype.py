LINE_LIMITS: dict[tuple[str, bool], tuple[int, int]] = {
    (FACT, False): (3, 8),
    (FACT, True): (2, 6),
    (SITUATION, False): (8, 14),
    (SITUATION, True): (5, 10),
    (OBJECTION, False): (6, 10),
    (OBJECTION, True): (4, 8),
    (FILE, False): (2, 4),
    (FILE, True): (1, 3),
    (OTHER, False): (6, 10),
    (OTHER, True): (3, 6),
}

DETAIL_LIMIT = 12


def format_block(kind: str, in_group: bool = False, detail: bool = False) -> str:
    """Блок «ФОРМАТ ОТВЕТА» — дописывается к вопросу, а не в кэшируемый системный префикс."""
    key = (kind if kind in ALL_TYPES else OTHER, in_group)
    rule = DETAIL_RULE if detail else _RULES[key]
    target, cap = (DETAIL_LIMIT, DETAIL_LIMIT + 4) if detail else LINE_LIMITS[key]
    where = " Ответ уйдёт в рабочий чат, где идёт живой разговор." if in_group and not detail else ""
    tail = (
        f"⚠️ И самое важное про длину: целься в {target} строк.{where} "
        f"Если тема правда требует больше — можно, но **потолок {cap} строк**, "
        f"за ним начинается выкладка. Не помещается в потолок — выбрасывай детали, "
        f"а не расширяй ответ. Растягивать ответ до потолка ради полноты не надо: "
        f"уложился в {target} — отлично."
    )
    return f"# ФОРМАТ ОТВЕТА (обязателен)\n\n{rule}\n\n{_COMMON}\n\n{tail}"


class Classifier:
    """Отдельный дешёвый вызов без каталога базы; если дешёвая модель не ответила, пробует основную."""

    def __init__(self, llm: LLMClient, model: str, fallback_model: str | None = None) -> None:
        self.llm = llm
        self.model = model
        self.fallback_model = fallback_model

    async def classify(self, question: str) -> tuple[str, Usage]:
        """Тип запроса и расход. Никогда не поднимает исключение: при сбое — ПРОЧЕЕ."""
        total = Usage()
        prompt = classifier_prompt(question)
        models = [self.model]
        if self.fallback_model and self.fallback_model != self.model:
            models.append(self.fallback_model)

        for model in models:
            try:
                completion = await self.llm.complete(
                    [{"type": "text", "text": CLASSIFIER_SYSTEM}],
                    [{"role": "user", "content": prompt}],
                    [],
                    model=model,
                )
            except Exception:
                log.warning("Классификатор (%s) не ответил", model, exc_info=True)
                continue
            _add(total, completion.usage)
            kind = parse_type(completion.text)
            if kind is not None:
                log.info(
                    "Тип запроса: %s (%s) | %s", LABELS[kind], model, question[:80]
                )
                return kind, total
            log.warning(
                "Классификатор (%s) ответил мимо списка: %r", model, (completion.text or "")[:80]
            )

        log.warning("Тип запроса не определён — отвечаю по формату ПРОЧЕЕ: %s", question[:80])
        return OTHER, total

    async def intent(self, message: str) -> tuple[str, Usage]:
        """Намерение обращения и расход. Никогда не поднимает исключение: при сомнении — ВОПРОС."""
        total = Usage()
        models = [self.model]
        if self.fallback_model and self.fallback_model != self.model:
            models.append(self.fallback_model)

        for model in models:
            try:
                completion = await self.llm.complete(
                    [{"type": "text", "text": INTENT_SYSTEM}],
                    [{"role": "user", "content": (message or "")[:MAX_QUESTION]}],
                    [],
                    model=model,
                )
            except Exception:
                log.warning("Определение намерения (%s) не сработало", model, exc_info=True)
                continue
            _add(total, completion.usage)
            found = parse_intent(completion.text)
            if found is not None:
                log.info("Намерение: %s | %s", INTENT_LABELS[found], (message or "")[:80])
                return found, total

        log.warning("Намерение не определено — считаю вопросом: %s", (message or "")[:80])
        return ASK, total


def _add(total: Usage, step: Usage) -> None:
    total.prompt_tokens += step.prompt_tokens
    total.completion_tokens += step.completion_tokens
    total.cached_tokens += step.cached_tokens
    total.cache_write_tokens += step.cache_write_tokens
    total.cost += step.cost
    total.cache_discount += step.cache_discount
